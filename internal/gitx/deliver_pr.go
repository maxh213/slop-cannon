// Safety-on delivery (D-10, D-20): the bead's branch is pushed to the
// default remote and a pull request is opened with gh. The default branch
// is never touched. The bead stays in `delivering`, records the PR in its
// metadata, and gets a gh:pr gate that blocks it until a human merges;
// dependents therefore wait for the merge, which is the point of safety.
// When gh cannot be used (not installed, not authenticated, or the remote
// is not on GitHub) the branch is still pushed, the human gets the compare
// URL, and the bead moves to `needs_human` because no gate can be checked.
// With no remote at all the branch is left in the repository and the bead
// moves to `needs_human` as well.

// PRMarker is the trailer line of every generated pull request body.
const PRMarker = "Generated by slop-cannon"

// prLabelColor and prLabelDescription define [CannonPRLabel] when it has
// to be created in the repository.
const (
	prLabelColor       = "6f42c1"
	prLabelDescription = "Pull request opened by slop-cannon"
)

// maxPRTitleLen caps the title passed to gh (GitHub rejects longer ones).
const maxPRTitleLen = 240

// Delivery sentinel errors. They match with errors.Is even when wrapped.
var (
	// ErrBranchMissing means the bead's branch (see [BranchName]) does not
	// exist in the repository, so there is nothing to deliver.
	ErrBranchMissing = errors.New("gitx: bead branch does not exist")
	// ErrPushRejected means the remote refused the push (non-fast-forward
	// or a protected branch); the wrapped [*GitError] carries git's text.
	ErrPushRejected = errors.New("gitx: push rejected by the remote")
)

// PRStatus classifies the outcome of [PRDeliverer.Deliver].
type PRStatus string

const (
	// PRCreated means the branch was pushed and a new pull request opened.
	PRCreated PRStatus = "created"
	// PRExisting means the branch was pushed and a pull request for it
	// already existed (a retry after an interrupted delivery); it was
	// reused.
	PRExisting PRStatus = "existing"
	// PRPushOnly means the branch was pushed but gh could not open a pull
	// request, so the human has to; the bead was moved to needs_human.
	PRPushOnly PRStatus = "push-only"
	// PRNoRemote means the repository has no remote; the branch was left
	// in place and the bead moved to needs_human.
	PRNoRemote PRStatus = "no-remote"
)

// PRTracker is the slice of the beads client the delivery needs to record
// the pull request on the bead (D-06) and to gate it (D-20).
// *beads.Client satisfies it.
type PRTracker interface {
	// SetMetadata merges meta into the bead's metadata.
	SetMetadata(ctx context.Context, id domain.BeadID, meta map[string]any) (beads.Issue, error)
	// SetStatus moves the bead to a workflow status.
	SetStatus(ctx context.Context, id domain.BeadID, state domain.BeadState) (beads.Issue, error)
	// CreatePRGate creates the gh:pr gate blocking the bead.
	CreatePRGate(ctx context.Context, bead domain.BeadID, prNumber int, reason string) (beads.Gate, error)
	// GateFor returns the open gate blocking the bead, or beads.ErrNoGate.
	GateFor(ctx context.Context, bead domain.BeadID) (beads.Gate, error)
}

var _ PRTracker = (*beads.Client)(nil)

// PRRequest describes one bead to deliver.
type PRRequest struct {
	// Bead is the bead whose branch (see [BranchName]) is delivered. ID and
	// Title are required; Type and Priority appear in the body when set.
	Bead domain.Bead
	// Run is the run the bead belongs to; shown in the body.
	Run domain.RunID
	// Report is the engineer's final implementation report, or nil.
	Report *domain.ImplReport
	// Verdicts are the testers' final verdicts, one per lens.
	Verdicts []domain.Verdict
	// Rounds is the number of review rounds the bead went through.
	Rounds int
	// Base overrides the branch the pull request targets; empty means the
	// repository's default branch.
	Base string
}

// PRResult is what [PRDeliverer.Deliver] did.
type PRResult struct {
	// Status classifies the outcome.
	Status PRStatus
	// Bead is the delivered bead.
	Bead domain.BeadID
	// Branch is the pushed branch and Head the commit at its tip.
	Branch string
	Head   string
	// Base is the branch the pull request targets.
	Base string
	// Remote is the remote pushed to and RemoteURL its fetch URL; both are
	// empty for PRNoRemote.
	Remote    string
	RemoteURL string
	// Pushed is true when the branch reached the remote.
	Pushed bool
	// PR is the pull request, for PRCreated and PRExisting.
	PR *PullRequest
	// PRState is gh's state of PR: "OPEN" for a new one, "OPEN" or
	// "MERGED" for a reused one.
	PRState string
	// Gate is the gh:pr gate blocking the bead, for PRCreated and
	// PRExisting.
	Gate domain.BeadID
	// State is the bead's workflow state after delivery: delivering when a
	// gate watches the pull request, needs_human otherwise.
	State domain.BeadState
	// Reason explains a PRPushOnly or PRNoRemote outcome.
	Reason string
	// Instructions tell the human what to do for PRPushOnly and PRNoRemote
	// (the compare URL when the remote is on GitHub).
	Instructions string
	// Warnings lists problems that did not stop the delivery (the label
	// could not be created, a stale gate exists).
	Warnings []string
}

// Summary renders one human-readable line describing the outcome.
func (r *PRResult) Summary() string {
	switch r.Status {
	case PRCreated:
		return fmt.Sprintf("%s: opened PR #%d %s (gate %s)", r.Bead, r.PR.Number, r.PR.URL, r.Gate)
	case PRExisting:
		return fmt.Sprintf("%s: reusing PR #%d %s (gate %s)", r.Bead, r.PR.Number, r.PR.URL, r.Gate)
	case PRPushOnly:
		return fmt.Sprintf("%s: pushed %s to %s but %s; %s", r.Bead, r.Branch, r.Remote, r.Reason, r.Instructions)
	case PRNoRemote:
		return fmt.Sprintf("%s: %s; %s", r.Bead, r.Reason, r.Instructions)
	}
	return fmt.Sprintf("%s: %s", r.Bead, r.Status)
}

// PRDeliverer pushes bead branches and opens pull requests for one run's
// worktree manager. It is safe for concurrent use; the orchestrator
// usually delivers one bead at a time anyway.
type PRDeliverer struct {
	m       *Manager
	tracker PRTracker
	gh      *GH
	logger  *slog.Logger
}

// PROption customises [NewPRDeliverer].
type PROption func(*PRDeliverer)

// WithPRLogger sets the logger delivery steps are reported to. The default
// is slog.Default().
func WithPRLogger(l *slog.Logger) PROption {
	return func(d *PRDeliverer) {
		if l != nil {
			d.logger = l
		}
	}
}

// WithPRGH sets the gh runner used to look up and open pull requests. The
// default is NewGH(m.Repo()).
func WithPRGH(gh *GH) PROption {
	return func(d *PRDeliverer) {
		if gh != nil {
			d.gh = gh
		}
	}
}

// NewPRDeliverer returns a deliverer for the manager's repository that
// records outcomes through tracker (normally the run's *beads.Client).
func NewPRDeliverer(m *Manager, tracker PRTracker, opts ...PROption) (*PRDeliverer, error) {
	if m == nil {
		return nil, errors.New("gitx: NewPRDeliverer: nil manager")
	}
	if tracker == nil {
		return nil, errors.New("gitx: NewPRDeliverer: nil tracker")
	}
	d := &PRDeliverer{m: m, tracker: tracker, logger: slog.Default()}
	for _, o := range opts {
		o(d)
	}
	if d.gh == nil {
		d.gh = NewGH(m.Repo())
	}
	return d, nil
}

// Deliver implements the safety-on path for one bead: push the bead's
// branch to the default remote, find or create the pull request for it
// (idempotent on retry), label it [CannonPRLabel], store sc_pr_url and
// sc_pr_number on the bead, and create the gh:pr gate that keeps the bead
// in delivering until the human merges (D-20). The caller is expected to
// have committed the engineer's leftovers (see [Manager.CommitLeftovers])
// and moved the bead to delivering; Deliver leaves the status alone on
// success.
//
// When gh is missing, not authenticated, or the remote is not on a GitHub
// host, the branch is still pushed, the result carries the compare URL or
// manual instructions, and the bead is moved to needs_human because no gate
// could be checked (Status PRPushOnly). Without a remote the branch stays
// local and the bead is moved to needs_human too (Status PRNoRemote).
// Neither is an error. Errors: [ErrBranchMissing], [ErrPushRejected], gh
// failures other than the ones above as [*GHError], and tracker errors.
//
// A hand-off leaves the bead in needs_human, so a later retry that does
// reach gh reports Status PRCreated and State delivering without writing
// that status: the caller owns the bead's status and must move it back to
// delivering itself, exactly as it does before the first delivery.
func (d *PRDeliverer) Deliver(ctx context.Context, req PRRequest) (*PRResult, error) {
	bead := req.Bead
	if bead.ID == "" {
		return nil, errors.New("gitx: Deliver: bead has no id")
	}
	repo := d.m.Repo()
	branch := BranchName(bead)
	log := d.logger.With("bead", string(bead.ID), "branch", branch)

	exists, err := repo.BranchExists(ctx, branch)
	if err != nil {
		return nil, err
	}
	if !exists {
		return nil, fmt.Errorf("%w: %s in %s", ErrBranchMissing, branch, repo.Root)
	}
	head, err := repo.RevParse(ctx, "refs/heads/"+branch)
	if err != nil {
		return nil, err
	}
	base := req.Base
	if base == "" {
		if base, err = repo.DefaultBranch(ctx); err != nil {
			return nil, err
		}
	}
	res := &PRResult{Bead: bead.ID, Branch: branch, Head: head, Base: base}

	remote, err := repo.DefaultRemote(ctx)
	if errors.Is(err, ErrNoRemote) {
		res.Status = PRNoRemote
		res.Reason = "the repository has no remote"
		res.Instructions = fmt.Sprintf("branch %s is left in %s; merge it into %s yourself", branch, repo.Root, base)
		return d.handOff(ctx, res, log)
	}
	if err != nil {
		return nil, err
	}
	res.Remote = remote
	if res.RemoteURL, err = repo.RemoteURL(ctx, remote); err != nil {
		return nil, err
	}

	log.InfoContext(ctx, "pushing bead branch", "remote", remote, "head", head)
	if err := repo.PushBranch(ctx, remote, branch); err != nil {
		return nil, err
	}
	res.Pushed = true

	pr, state, err := d.gh.FindPR(ctx, branch)
	if reason, ok := ghUnavailable(err); ok {
		res.Status = PRPushOnly
		res.Reason = reason
		res.Instructions = manualPRInstructions(res)
		return d.handOff(ctx, res, log)
	}
	if err != nil {
		return nil, err
	}
	if pr != nil {
		res.Status = PRExisting
		log.InfoContext(ctx, "reusing existing pull request", "number", pr.Number, "url", pr.URL, "state", state)
	} else {
		title := PRTitle(bead)
		body := PRBody(req, branch, base)
		created, warn, err := d.gh.CreatePR(ctx, PRSpec{Head: branch, Base: base, Title: title, Body: body, Labels: []string{CannonPRLabel}})
		if err != nil {
			return nil, err
		}
		if warn != "" {
			res.Warnings = append(res.Warnings, warn)
		}
		pr, state = created, "OPEN"
		res.Status = PRCreated
		log.InfoContext(ctx, "opened pull request", "number", pr.Number, "url", pr.URL)
	}
	res.PR, res.PRState = pr, state

	if _, err := d.tracker.SetMetadata(ctx, bead.ID, beads.PRMetadata(pr.URL, pr.Number)); err != nil {
		return nil, fmt.Errorf("gitx: recording PR on %s: %w", bead.ID, err)
	}
	gate, warn, err := d.ensureGate(ctx, bead, pr)
	if err != nil {
		return nil, err
	}
	if warn != "" {
		res.Warnings = append(res.Warnings, warn)
	}
	res.Gate = gate
	res.State = domain.BeadStateDelivering
	return res, nil
}

// handOff finishes a delivery no gate can watch: the bead moves to
// needs_human and the result says why.
func (d *PRDeliverer) handOff(ctx context.Context, res *PRResult, log *slog.Logger) (*PRResult, error) {
	log.WarnContext(ctx, "pull request needs a human", "status", string(res.Status), "reason", res.Reason, "instructions", res.Instructions)
	if _, err := d.tracker.SetStatus(ctx, res.Bead, domain.BeadStateNeedsHuman); err != nil {
		return nil, fmt.Errorf("gitx: moving %s to %s: %w", res.Bead, domain.BeadStateNeedsHuman, err)
	}
	res.State = domain.BeadStateNeedsHuman
	return res, nil
}

// ensureGate returns the gh:pr gate for pr, creating it unless an open one
// for the same number already blocks the bead. A gate for another PR is
// left alone and reported as a warning.
func (d *PRDeliverer) ensureGate(ctx context.Context, bead domain.Bead, pr *PullRequest) (domain.BeadID, string, error) {
	warn := ""
	existing, err := d.tracker.GateFor(ctx, bead.ID)
	switch {
	case err == nil:
		if n, ok := existing.PRNumber(); ok && n == pr.Number {
			return existing.ID, "", nil
		}
		warn = fmt.Sprintf("bead %s is already blocked by gate %s (%s %s), which is not for PR #%d", bead.ID, existing.ID, existing.AwaitType, existing.AwaitID, pr.Number)
	case errors.Is(err, beads.ErrNoGate):
	default:
		return "", "", fmt.Errorf("gitx: looking up the gate of %s: %w", bead.ID, err)
	}
	reason := fmt.Sprintf("PR #%d: %s", pr.Number, PRTitle(bead))
	gate, err := d.tracker.CreatePRGate(ctx, bead.ID, pr.Number, reason)
	if err != nil {
		return "", "", fmt.Errorf("gitx: creating the gh:pr gate for %s: %w", bead.ID, err)
	}
	return gate.ID, warn, nil
}

// manualPRInstructions tells the human how to open the pull request by
// hand: the GitHub compare URL when the remote is on GitHub, otherwise the
// branches and remote involved.
func manualPRInstructions(res *PRResult) string {
	if u := CompareURL(res.RemoteURL, res.Base, res.Branch); u != "" {
		return "open the pull request yourself: " + u
	}
	return fmt.Sprintf("open a pull request from %s to %s on %s (%s) yourself", res.Branch, res.Base, res.Remote, res.RemoteURL)
}

// PRTitle returns the pull request title for a bead: its title with
// whitespace collapsed, capped at [maxPRTitleLen] bytes on a rune
// boundary (so the title stays valid UTF-8), or "Bead <id>" when the bead
// has no title.
func PRTitle(bead domain.Bead) string {
	title := strings.Join(strings.Fields(bead.Title), " ")
	if title == "" {
		return "Bead " + string(bead.ID)
	}
	if len(title) > maxPRTitleLen {
		const ellipsis = "…"
		cut := maxPRTitleLen - len(ellipsis)
		for cut > 0 && !utf8.RuneStart(title[cut]) {
			cut--
		}
		title = strings.TrimSpace(title[:cut]) + ellipsis
	}
	return title
}

// PRBody renders the pull request description in Markdown: a machine
// readable marker comment, the bead section (id, title, run, branches),
// the implementation report, one row per tester verdict, the number of
// review rounds, and the [PRMarker] trailer.
func PRBody(req PRRequest, branch, base string) string {
	bead := req.Bead
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- slop-cannon bead=%s run=%s branch=%s -->\n", bead.ID, req.Run, branch)

	b.WriteString("## Bead\n\n")
	fmt.Fprintf(&b, "- **ID**: `%s` (`bd show %s`)\n", bead.ID, bead.ID)
	if t := strings.TrimSpace(bead.Title); t != "" {
		fmt.Fprintf(&b, "- **Title**: %s\n", t)
	}
	if bead.Type != "" {
		fmt.Fprintf(&b, "- **Type**: %s, priority %d\n", bead.Type, bead.Priority)
	}
	if req.Run != "" {
		fmt.Fprintf(&b, "- **Run**: `%s`\n", req.Run)
	}
	fmt.Fprintf(&b, "- **Branch**: `%s` into `%s`\n", branch, base)
	if a := strings.TrimSpace(bead.Acceptance); a != "" {
		b.WriteString("\n**Acceptance criteria**\n\n")
		b.WriteString(a)
		b.WriteString("\n")
	}

	b.WriteString("\n## Implementation report\n\n")
	if r := req.Report; r == nil {
		b.WriteString("_No implementation report was recorded._\n")
	} else {
		if s := strings.TrimSpace(r.Summary); s != "" {
			b.WriteString(s)
			b.WriteString("\n")
		}
		writeList(&b, "Files changed", r.FilesChanged, true)
		if v := strings.TrimSpace(r.HowToVerify); v != "" {
			b.WriteString("\n**How to verify**\n\n")
			b.WriteString(v)
			b.WriteString("\n")
		}
		writeList(&b, "Risks", r.Risks, false)
		writeList(&b, "Open questions", r.Questions, false)
	}

	b.WriteString("\n## Review\n\n")
	if len(req.Verdicts) == 0 {
		b.WriteString("_No tester verdicts were recorded._\n")
	} else {
		b.WriteString("| Lens | Round | Verdict | Summary |\n|---|---|---|---|\n")
		for _, v := range req.Verdicts {
			lens := string(v.Lens)
			if lens == "" {
				lens = "-"
			}
			fmt.Fprintf(&b, "| %s | %d | %s | %s |\n", cell(lens), v.Round, cell(string(v.Outcome)), cell(v.Summary))
		}
	}

	fmt.Fprintf(&b, "\n## Rounds\n\n%d review %s.\n", req.Rounds, plural(req.Rounds, "round", "rounds"))
	b.WriteString("\n---\n" + PRMarker + "\n")
	return b.String()
}

// writeList renders a bold heading and a bullet list, or nothing when the
// list is empty. Items are wrapped in backticks when code is set.
func writeList(b *strings.Builder, heading string, items []string, code bool) {
	var kept []string
	for _, it := range items {
		if it = strings.TrimSpace(it); it != "" {
			kept = append(kept, it)
		}
	}
	if len(kept) == 0 {
		return
	}
	fmt.Fprintf(b, "\n**%s**\n\n", heading)
	for _, it := range kept {
		if code {
			fmt.Fprintf(b, "- `%s`\n", it)
		} else {
			fmt.Fprintf(b, "- %s\n", it)
		}
	}
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

// PushBranch pushes the local branch to remote under the same name with
// "git push --quiet <remote> refs/heads/<branch>:refs/heads/<branch>". No
// upstream is configured, so nothing is written to the repository's
// config. A push the remote refuses fails with [ErrPushRejected].
func (r *Repo) PushBranch(ctx context.Context, remote, branch string) error {
	if remote == "" || branch == "" {
		return errors.New("gitx: PushBranch: empty remote or branch")
	}
	ref := "refs/heads/" + branch
	_, err := r.Git(ctx, "push", "--quiet", "--", remote, ref+":"+ref)
	if err != nil {
		var ge *GitError
		if errors.As(err, &ge) && strings.Contains(ge.Stderr, "[rejected]") {
			ge.Cause = ErrPushRejected
		}
		return err
	}
	return nil
}

// RemoteURL returns the fetch URL of remote.
func (r *Repo) RemoteURL(ctx context.Context, remote string) (string, error) {
	return r.Git(ctx, "remote", "get-url", "--", remote)
}

// ghUnavailable classifies an error from [GH] as "gh cannot be used
// here": not installed, not authenticated, or no GitHub remote. Other
// failures (network, rate limits, a bad argument) are not.
func ghUnavailable(err error) (string, bool) {
	switch {
	case err == nil:
		return "", false
	case errors.Is(err, ErrGHNotFound) || proc.IsNotFound(err):
		return "gh is not installed", true
	case errors.Is(err, ErrNoGitHubRemote):
		return "the remote is not on a GitHub host gh knows", true
	case errors.Is(err, ErrGHUnauthenticated):
		return "gh is not authenticated (run `gh auth login`)", true
	}
	return "", false
}

// ghPRRef is the raw gh JSON shape of `gh pr list --json number,url,state,title`.
type ghPRRef struct {
	Number int    `json:"number"`
	URL    string `json:"url"`
	State  string `json:"state"`
	Title  string `json:"title"`
}

// FindPR looks up the pull request whose head is branch with
// "gh pr list --head <branch> --state all". An open one wins; otherwise a
// merged one is returned so the gate resolves immediately; a closed,
// unmerged one is ignored so a retry opens a fresh pull request. state is
// gh's "OPEN" or "MERGED"; the result is nil when there is none.
func (g *GH) FindPR(ctx context.Context, branch string) (pr *PullRequest, state string, err error) {
	if branch == "" {
		return nil, "", errors.New("gitx: FindPR: empty branch")
	}
	out, err := g.run(ctx, "", "pr", "list", "--head", branch, "--state", "all", "--limit", "50", "--json", "number,url,state,title")
	if err != nil {
		return nil, "", err
	}
	var refs []ghPRRef
	if strings.TrimSpace(out) != "" {
		if err := json.Unmarshal([]byte(out), &refs); err != nil {
			return nil, "", fmt.Errorf("gitx: gh pr list: unexpected output %q: %w", out, err)
		}
	}
	// Newest first, so among several of one state the latest wins.
	sort.SliceStable(refs, func(i, j int) bool { return refs[i].Number > refs[j].Number })
	for _, want := range []string{"OPEN", "MERGED"} {
		for _, ref := range refs {
			if strings.EqualFold(ref.State, want) {
				return &PullRequest{Number: ref.Number, URL: ref.URL, Title: ref.Title, HeadRef: branch}, want, nil
			}
		}
	}
	return nil, "", nil
}

// PRSpec describes a pull request to open with [GH.CreatePR].
type PRSpec struct {
	// Head is the branch holding the work; Base the branch it targets.
	Head, Base string
	// Title and Body are the pull request title and Markdown description.
	Title, Body string
	// Labels are attached to the pull request; missing ones are created in
	// the repository first.
	Labels []string
}

// CreatePR opens a pull request with "gh pr create". Every label in
// spec.Labels is created in the repository beforehand ("gh label create
// --force", an update when it exists); when that fails the pull request is
// opened without labels and the warning says so. The body is passed on
// standard input ("--body-file -"), so its size is not bound by the
// argument limit. The returned pull request carries the number parsed
// from the URL gh prints.
func (g *GH) CreatePR(ctx context.Context, spec PRSpec) (pr *PullRequest, warning string, err error) {
	if spec.Head == "" || spec.Base == "" {
		return nil, "", errors.New("gitx: CreatePR: empty head or base")
	}
	if strings.TrimSpace(spec.Title) == "" {
		return nil, "", errors.New("gitx: CreatePR: empty title")
	}
	labels := spec.Labels
	for _, label := range spec.Labels {
		if _, err := g.run(ctx, "", "label", "create", label, "--color", prLabelColor, "--description", prLabelDescription, "--force"); err != nil {
			warning = fmt.Sprintf("could not create label %q, opening the pull request without labels: %v", label, err)
			labels = nil
			break
		}
	}
	body := spec.Body
	if body == "" {
		body = PRMarker + "\n"
	}
	args := []string{"pr", "create", "--head", spec.Head, "--base", spec.Base, "--title", spec.Title, "--body-file", "-"}
	for _, label := range labels {
		args = append(args, "--label", label)
	}
	out, err := g.run(ctx, body, args...)
	if err != nil {
		return nil, warning, err
	}
	pr, err = parseCreatedPR(out)
	if err != nil {
		return nil, warning, err
	}
	pr.Title, pr.HeadRef, pr.BaseRef = spec.Title, spec.Head, spec.Base
	pr.Labels = append(pr.Labels, labels...)
	return pr, warning, nil
}

// parseCreatedPR extracts the pull request URL and number from the output
// of "gh pr create", whose last line is the URL.
func parseCreatedPR(out string) (*PullRequest, error) {
	lines := strings.Split(strings.TrimSpace(out), "\n")
	for i := len(lines) - 1; i >= 0; i-- {
		line := strings.TrimSpace(lines[i])
		if !strings.HasPrefix(line, "http://") && !strings.HasPrefix(line, "https://") {
			continue
		}
		n, err := strconv.Atoi(path.Base(line))
		if err != nil || n <= 0 {
			return nil, fmt.Errorf("gitx: gh pr create: cannot read the PR number from %q", line)
		}
		return &PullRequest{Number: n, URL: line}, nil
	}
	return nil, fmt.Errorf("gitx: gh pr create: no pull request URL in output %q", out)
}

// ParseGitHubRemote splits a GitHub remote URL (https://, ssh://, git://,
// or the scp-like git@host:owner/name form) into host, owner, and
// repository name, with a trailing ".git" removed. ok is false for URLs of
// another shape or for hosts that are not GitHub (github.com or a host
// whose name contains "github", as GitHub Enterprise hosts usually do).
func ParseGitHubRemote(remote string) (host, owner, name string, ok bool) {
	remote = strings.TrimSpace(remote)
	var p string
	switch {
	case strings.Contains(remote, "://"):
		u, err := url.Parse(remote)
		if err != nil || u.Host == "" {
			return "", "", "", false
		}
		host, p = u.Hostname(), u.Path
	default:
		// scp-like: [user@]host:owner/name
		i := strings.Index(remote, ":")
		if i <= 0 || strings.Contains(remote[:i], "/") {
			return "", "", "", false
		}
		host, p = remote[:i], remote[i+1:]
		if at := strings.LastIndex(host, "@"); at >= 0 {
			host = host[at+1:]
		}
	}
	host = strings.ToLower(host)
	if host != "github.com" && !strings.Contains(host, "github") {
		return "", "", "", false
	}
	parts := strings.Split(strings.Trim(p, "/"), "/")
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return "", "", "", false
	}
	name = strings.TrimSuffix(parts[1], ".git")
	if name == "" {
		return "", "", "", false
	}
	return host, parts[0], name, true
}

// CompareURL returns the GitHub page that opens a pull request from head
// into base for the repository at remote
// ("https://<host>/<owner>/<name>/compare/<base>...<head>?expand=1"), or
// "" when remote is not a GitHub URL (see [ParseGitHubRemote]).
func CompareURL(remote, base, head string) string {
	host, owner, name, ok := ParseGitHubRemote(remote)
	if !ok || base == "" || head == "" {
		return ""
	}
	return fmt.Sprintf("https://%s/%s/%s/compare/%s...%s?expand=1", host, owner, name, escapeRef(base), escapeRef(head))
}

// escapeRef escapes a branch name for a URL path while keeping its slashes.
func escapeRef(ref string) string {
	parts := strings.Split(ref, "/")
	for i, p := range parts {
		parts[i] = url.PathEscape(p)
	}
	return strings.Join(parts, "/")
}
