// amOwner is the ownership a pull request for wtBead in run "run-1" must
// match; amOwnedPR passes every clause of it.
func amOwner() Ownership {
	return Ownership{
		Bead: wtBead.ID, Run: "run-1", Branch: "sc/fx-a0u-fix-the-mean-bug", Base: "main",
		PRNumber: 7, RunStarted: dpStarted, Login: dpLogin,
	}
}

func amOwnedPR() PullRequest {
	return PullRequest{
		Number: 7, HeadRef: "sc/fx-a0u-fix-the-mean-bug", BaseRef: "main",
		Labels:    []string{"bug", CannonPRLabel},
		Body:      "<!-- slop-cannon bead=fx-a0u run=run-1 branch=sc/fx-a0u-fix-the-mean-bug -->\n## Bead\n",
		Author:    dpLogin,
		CreatedAt: dpStarted.Add(time.Minute),
	}
}

// TestOwnedByRun breaks the D-31 ownership predicate one clause at a time:
// every clause on its own is enough to make a pull request not the run's,
// and an unknown value fails its clause instead of passing it.
func TestOwnedByRun(t *testing.T) {
	ok, why := OwnedByRun(amOwnedPR(), amOwner())
	require.True(t, ok, why)
	assert.Empty(t, why)

	upper := amOwnedPR()
	upper.Labels, upper.Author = []string{"Slop-Cannon"}, strings.ToUpper(dpLogin)
	ok, why = OwnedByRun(upper, amOwner())
	assert.True(t, ok, "GitHub compares labels and logins case-insensitively: %s", why)

	cases := []struct {
		name  string
		pr    func(*PullRequest)
		owner func(*Ownership)
		want  string
	}{
		{name: "another branch", pr: func(p *PullRequest) { p.HeadRef = "sc/fx-a0u-fix-the-mean-bug-2" }, want: "head branch"},
		{name: "a human's branch", pr: func(p *PullRequest) { p.HeadRef = "fix-mean" }, want: "head branch"},
		{name: "no expected branch", owner: func(o *Ownership) { o.Branch = "" }, want: "head branch"},
		{name: "another base", pr: func(p *PullRequest) { p.BaseRef = "release" }, want: "base branch"},
		{name: "no label", pr: func(p *PullRequest) { p.Labels = []string{"bug"} }, want: "label"},
		{name: "no marker", pr: func(p *PullRequest) { p.Body = "Fixes the mean." }, want: "no slop-cannon marker"},
		{name: "another run", pr: func(p *PullRequest) {
			p.Body = strings.Replace(p.Body, "run=run-1", "run=run-0", 1)
		}, want: "names run"},
		{name: "an empty run", pr: func(p *PullRequest) {
			p.Body = strings.Replace(p.Body, "run=run-1", "run=", 1)
		}, want: "names run"},
		{name: "another bead", pr: func(p *PullRequest) {
			p.Body = strings.Replace(p.Body, "bead=fx-a0u", "bead=fx-zzz", 1)
		}, want: "names bead"},
		{name: "another number", pr: func(p *PullRequest) { p.Number = 8 }, want: "not the bead's recorded pull request #7"},
		{name: "no recorded number", owner: func(o *Ownership) { o.PRNumber = 0 }, want: "recorded pull request"},
		{name: "created before the run", pr: func(p *PullRequest) { p.CreatedAt = dpStarted.Add(-time.Second) }, want: "before this run started"},
		{name: "no creation time", pr: func(p *PullRequest) { p.CreatedAt = time.Time{} }, want: "an unknown time"},
		{name: "no run start", owner: func(o *Ownership) { o.RunStarted = time.Time{} }, want: "before this run started"},
		{name: "another author", pr: func(p *PullRequest) { p.Author = "mallory" }, want: "author"},
		{name: "no login", owner: func(o *Ownership) { o.Login = "" }, want: "author"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			pr, o := amOwnedPR(), amOwner()
			if tc.pr != nil {
				tc.pr(&pr)
			}
			if tc.owner != nil {
				tc.owner(&o)
			}
			ok, why := OwnedByRun(pr, o)
			assert.False(t, ok)
			assert.Contains(t, why, tc.want)
		})
	}
}

