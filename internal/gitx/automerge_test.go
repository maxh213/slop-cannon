// amView is a `gh pr view --json <ghPRViewFields>` answer whose rollup
// holds the given raw entries.
func amView(entries ...string) string {
	return `{"number":7,"state":"OPEN","isDraft":false,"headRefName":"sc/fx-a0u-fix-the-mean-bug",
"headRefOid":"abc123","baseRefName":"main","mergeable":"MERGEABLE","mergeStateStatus":"CLEAN",
"labels":[{"name":"slop-cannon"}],"body":"<!-- slop-cannon bead=fx-a0u run=run-1 branch=sc/fx-a0u-fix-the-mean-bug -->",
"createdAt":"2026-09-01T13:00:00Z","author":{"login":"sc-bot"},"statusCheckRollup":[` + strings.Join(entries, ",") + `]}`
}

func amRun(name, status, conclusion string) string {
	return fmt.Sprintf(`{"__typename":"CheckRun","name":%q,"status":%q,"conclusion":%q,"detailsUrl":"https://ci.example/%s"}`, name, status, conclusion, name)
}

func amStatus(context, state string) string {
	return fmt.Sprintf(`{"__typename":"StatusContext","context":%q,"state":%q,"targetUrl":"https://ci.example/%s"}`, context, state, context)
}

func TestParsePRViewAndJudgeTheRollup(t *testing.T) {
	v, err := ParsePRView([]byte(amView(amRun("test", "COMPLETED", "SUCCESS"), amStatus("deploy/preview", "SUCCESS"))))
	require.NoError(t, err)
	assert.Equal(t, 7, v.Number)
	assert.Equal(t, "OPEN", v.State)
	assert.Equal(t, "abc123", v.HeadSHA)
	assert.Equal(t, "CLEAN", v.MergeStateStatus)
	assert.Equal(t, "MERGEABLE", v.Mergeable)
	assert.Equal(t, dpLogin, v.Author)
	assert.Equal(t, []string{CannonPRLabel}, v.Labels)
	assert.Equal(t, time.Date(2026, 9, 1, 13, 0, 0, 0, time.UTC), v.CreatedAt)
	require.Len(t, v.Checks, 2)
	assert.Equal(t, PRCheck{Kind: CheckKindRun, Name: "test", Status: "COMPLETED", Conclusion: "SUCCESS", URL: "https://ci.example/test"}, v.Checks[0])
	assert.Equal(t, PRCheck{Kind: CheckKindStatus, Name: "deploy/preview", State: "SUCCESS", URL: "https://ci.example/deploy/preview"}, v.Checks[1])

	cases := []struct {
		name     string
		entries  []string
		required []string
		green    bool
		pending  int
		failed   []string
		missing  []string
	}{
		{name: "green", entries: []string{amRun("test", "COMPLETED", "SUCCESS")}, green: true},
		{name: "neutral and skipped pass the rollup", entries: []string{amRun("a", "COMPLETED", "NEUTRAL"), amRun("b", "COMPLETED", "SKIPPED"), amRun("c", "COMPLETED", "SUCCESS")}, green: true},
		{name: "an empty rollup is never green"},
		{name: "in progress", entries: []string{amRun("test", "IN_PROGRESS", ""), amRun("build", "COMPLETED", "SUCCESS")}, pending: 1},
		{name: "queued", entries: []string{amRun("test", "QUEUED", "")}, pending: 1},
		{name: "a status still pending", entries: []string{amStatus("ci", "PENDING")}, pending: 1},
		{name: "an expected status", entries: []string{amStatus("ci", "EXPECTED")}, pending: 1},
		{name: "a stale conclusion waits", entries: []string{amRun("test", "COMPLETED", "STALE")}, pending: 1},
		{name: "an unknown conclusion waits", entries: []string{amRun("test", "COMPLETED", "")}, pending: 1},
		{name: "failure", entries: []string{amRun("test", "COMPLETED", "FAILURE"), amRun("build", "COMPLETED", "SUCCESS")}, failed: []string{"test"}},
		{name: "every failed conclusion", entries: []string{
			amRun("a", "COMPLETED", "ERROR"), amRun("b", "COMPLETED", "CANCELLED"), amRun("c", "COMPLETED", "TIMED_OUT"),
			amRun("d", "COMPLETED", "ACTION_REQUIRED"), amRun("e", "COMPLETED", "STARTUP_FAILURE"), amRun("f", "COMPLETED", "FAILURE"),
		}, failed: []string{"a", "b", "c", "d", "e", "f"}},
		{name: "a failed status", entries: []string{amStatus("ci", "FAILURE"), amStatus("lint", "ERROR")}, failed: []string{"ci", "lint"}},
		{name: "a required check that is there", entries: []string{amRun("test", "COMPLETED", "SUCCESS"), amStatus("build", "SUCCESS")}, required: []string{"test", "build"}, green: true},
		{name: "a required check that has not reported", entries: []string{amRun("test", "COMPLETED", "SUCCESS")}, required: []string{"test", "build"}, missing: []string{"build"}},
		{name: "a required check that was skipped did not succeed", entries: []string{amRun("test", "COMPLETED", "SKIPPED"), amRun("x", "COMPLETED", "SUCCESS")}, required: []string{"test"}, missing: []string{"test"}},
		{name: "blank required names are ignored", entries: []string{amRun("test", "COMPLETED", "SUCCESS")}, required: []string{" ", ""}, green: true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			v, err := ParsePRView([]byte(amView(tc.entries...)))
			require.NoError(t, err)
			s := v.Summary(tc.required)
			assert.Equal(t, tc.green, s.Green())
			assert.Len(t, s.Pending, tc.pending)
			var failed []string
			for _, c := range s.Failed {
				failed = append(failed, c.Name)
			}
			assert.Equal(t, tc.failed, failed)
			assert.Equal(t, tc.missing, s.Missing)
		})
	}
}

// TestGHAutoMergeCommands pins the exact command lines D-31 allows: the
// merge is a squash that names the head commit and nothing else, the
// branch update is GitHub's own, and the login is read once.
func TestGHAutoMergeCommands(t *testing.T) {
	ctx := context.Background()
	f := dpSetup(t, true)
	gh := f.d.GH()

	require.NoError(t, gh.MergePR(ctx, 7, "abc123"))
	require.NoError(t, gh.UpdateBranch(ctx, 7))
	dpSet(t, f.gh, "view.json", amView(amRun("test", "COMPLETED", "SUCCESS")))
	v, err := gh.ViewPR(ctx, 7)
	require.NoError(t, err)
	assert.Equal(t, "abc123", v.HeadSHA)
	for range 2 {
		login, err := gh.Login(ctx)
		require.NoError(t, err)
		assert.Equal(t, dpLogin, login)
	}

	calls := f.gh.Invocations(t)
	require.Len(t, calls, 4, "the login is read once and cached")
	assert.Equal(t, []string{"pr", "merge", "7", "--squash", "--match-head-commit", "abc123"}, calls[0].Args)
	assert.Equal(t, []string{"pr", "update-branch", "7"}, calls[1].Args)
	assert.Equal(t, []string{"pr", "view", "7", "--json",
		"number,state,isDraft,headRefName,headRefOid,baseRefName,mergeable,mergeStateStatus,statusCheckRollup,labels,body,createdAt,author"}, calls[2].Args)
	assert.Equal(t, []string{"api", "user", "--jq", ".login"}, calls[3].Args)

	require.ErrorIs(t, gh.MergePR(ctx, 7, " "), ErrNoHeadCommit, "a merge never goes out without the head it was judged on")
	require.Error(t, gh.MergePR(ctx, 0, "abc123"))
	require.Error(t, gh.UpdateBranch(ctx, -1))
	assert.Len(t, f.gh.Invocations(t), 4, "a refused merge reaches no gh")

	// A login that cannot be read is not cached.
	fresh := NewGH(f.repo)
	dpSet(t, f.gh, "login-fails", "")
	_, err = fresh.Login(ctx)
	require.Error(t, err)
	require.NoError(t, os.Remove(filepath.Join(f.gh.Dir, "login-fails")))
	login, err := fresh.Login(ctx)
	require.NoError(t, err)
	assert.Equal(t, dpLogin, login)
}

// TestPRDelivererNeverAdoptsAPullRequestThatIsNotTheRunsOwn is the D-31
// adoption hole closed: an open or merged pull request for the bead's
// branch that fails any ownership clause is not reused, its branch is not
// pushed to, nothing is created, and the bead goes to a person.
func TestPRDelivererNeverAdoptsAPullRequestThatIsNotTheRunsOwn(t *testing.T) {
	ctx := context.Background()
	cases := []struct {
		name  string
		state string
		edit  func(map[string]any)
		req   func(*PRRequest)
		want  string
	}{
		{name: "a human's pull request from before the run", state: "OPEN", edit: func(pr map[string]any) {
			pr["createdAt"] = dpStarted.Add(-24 * time.Hour).Format(time.RFC3339)
		}, want: "before this run started"},
		{name: "a merged pull request from before the run", state: "MERGED", edit: func(pr map[string]any) {
			pr["createdAt"] = dpStarted.Add(-time.Minute).Format(time.RFC3339)
		}, want: "before this run started"},
		{name: "another author", state: "OPEN", edit: func(pr map[string]any) { pr["author"] = map[string]string{"login": "mallory"} }, want: "author"},
		{name: "no label", state: "OPEN", edit: func(pr map[string]any) { pr["labels"] = []any{} }, want: "label"},
		{name: "no marker", state: "OPEN", edit: func(pr map[string]any) { pr["body"] = "hand-written" }, want: "marker"},
		{name: "another run's marker", state: "OPEN", edit: func(pr map[string]any) {
			pr["body"] = strings.Replace(fmt.Sprint(pr["body"]), "run=run-1", "run=20260101-000000-0000", 1)
		}, want: "names run"},
		{name: "another bead's marker", state: "OPEN", edit: func(pr map[string]any) {
			pr["body"] = strings.Replace(fmt.Sprint(pr["body"]), "bead=fx-a0u", "bead=fx-b1v", 1)
		}, want: "names bead"},
		{name: "another base", state: "OPEN", edit: func(pr map[string]any) { pr["baseRefName"] = "release" }, want: "base branch"},
		{name: "another head", state: "OPEN", edit: func(pr map[string]any) { pr["headRefName"] = "fix-mean" }, want: "head branch"},
		{name: "not the number the bead recorded", state: "OPEN", req: func(r *PRRequest) { r.Bead.PRNumber = 4 }, want: "recorded pull request #4"},
		{name: "a run with no start time", state: "OPEN", req: func(r *PRRequest) { r.RunStarted = time.Time{} }, want: "before this run started"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			f := dpSetup(t, true)
			dpSet(t, f.gh, "prs.json", dpPRs(dpPR(t, 5, tc.state, f.wt.Branch, tc.edit)))
			remoteBefore := dpRemoteHeads(t, f)
			req := dpRequest()
			if tc.req != nil {
				tc.req(&req)
			}

			res, err := f.d.Deliver(ctx, req)
			require.NoError(t, err)
			assert.Equal(t, PRForeign, res.Status)
			assert.Equal(t, domain.BeadStateNeedsHuman, res.State)
			assert.Contains(t, res.Reason, "pull request #5")
			assert.Contains(t, res.Reason, tc.want)
			assert.Contains(t, res.Instructions, "will not push to, reuse or merge it")
			assert.False(t, res.Pushed)
			assert.Equal(t, remoteBefore, dpRemoteHeads(t, f), "nothing is pushed to a branch the run does not own")
			assert.NotContains(t, dpCalls(t, f.gh), "pr create")
			assert.Empty(t, f.tracker.meta, "the pull request is not recorded on the bead")
			assert.Empty(t, f.tracker.created, "no gate watches it")
			assert.Equal(t, []domain.BeadState{domain.BeadStateNeedsHuman}, f.tracker.statuses)
			assert.Contains(t, res.Summary(), "not this run's own")
		})
	}

	t.Run("a login gh cannot read is an error, and nothing is pushed", func(t *testing.T) {
		f := dpSetup(t, true)
		dpSet(t, f.gh, "prs.json", dpPRs(dpPR(t, 5, "OPEN", f.wt.Branch, nil)))
		dpSet(t, f.gh, "login-fails", "")
		remoteBefore := dpRemoteHeads(t, f)
		_, err := f.d.Deliver(ctx, dpRequest())
		require.Error(t, err)
		assert.Equal(t, remoteBefore, dpRemoteHeads(t, f))
		assert.Empty(t, f.tracker.statuses)
	})

	t.Run("a login gh rejects as unauthenticated hands off, and nothing is pushed", func(t *testing.T) {
		// The pull request list worked a moment earlier, so the branch has
		// a pull request nobody has shown is the run's: gh being "down" now
		// must not turn the delivery into a push-only one onto it.
		f := dpSetup(t, true)
		dpSet(t, f.gh, "prs.json", dpPRs(dpPR(t, 5, "OPEN", f.wt.Branch, func(pr map[string]any) {
			pr["author"] = map[string]string{"login": "mallory"}
			pr["createdAt"] = dpStarted.Add(-24 * time.Hour).Format(time.RFC3339)
		})))
		dpSet(t, f.gh, "login-fails", "HTTP 401: Bad credentials (https://api.github.com/user)")
		remoteBefore := dpRemoteHeads(t, f)
		res, err := f.d.Deliver(ctx, dpRequest())
		require.NoError(t, err)
		assert.Equal(t, PRForeign, res.Status)
		assert.Equal(t, domain.BeadStateNeedsHuman, res.State)
		assert.Contains(t, res.Reason, "could not confirm pull request #5")
		assert.Contains(t, res.Reason, "not authenticated")
		assert.False(t, res.Pushed)
		assert.Equal(t, remoteBefore, dpRemoteHeads(t, f), "nothing is pushed to a branch the run has not shown it owns")
		assert.Empty(t, f.tracker.meta)
		assert.Equal(t, []domain.BeadState{domain.BeadStateNeedsHuman}, f.tracker.statuses)
	})

	t.Run("a foreign pull request with the same head name does not hide the run's own", func(t *testing.T) {
		// A fork's pull request matches `gh pr list --head <branch>` too,
		// and a newer one would be preferred if ownership were not judged
		// across every candidate.
		f := dpSetup(t, true)
		dpSet(t, f.gh, "prs.json", dpPRs(
			dpPR(t, 9, "OPEN", f.wt.Branch, func(pr map[string]any) { pr["author"] = map[string]string{"login": "mallory"} }),
			dpPR(t, 5, "OPEN", f.wt.Branch, nil),
		))
		req := dpRequest()
		req.Bead.PRNumber = 5
		res, err := f.d.Deliver(ctx, req)
		require.NoError(t, err)
		assert.Equal(t, PRExisting, res.Status)
		require.NotNil(t, res.PR)
		assert.Equal(t, 5, res.PR.Number)
		assert.True(t, res.Pushed)
		assert.Equal(t, domain.BeadStateDelivering, res.State)
	})

	t.Run("the run's own pull request with no number recorded yet is reused", func(t *testing.T) {
		// The delivery that opened it died before sc_pr_number was written;
		// every other clause ties it to this run.
		f := dpSetup(t, true)
		dpSet(t, f.gh, "prs.json", dpPRs(dpPR(t, 5, "OPEN", f.wt.Branch, nil)))
		res, err := f.d.Deliver(ctx, dpRequest())
		require.NoError(t, err)
		assert.Equal(t, PRExisting, res.Status)
		assert.True(t, res.Pushed)
	})
}

func TestConventionalPRTitle(t *testing.T) {
	cases := []struct {
		bead domain.Bead
		want string
	}{
		{domain.Bead{ID: "fx-1", Title: "Fix the mean() bug!", Type: domain.BeadTypeBug}, "fix: fix the mean() bug!"},
		{domain.Bead{ID: "fx-1", Title: "Add dark mode", Type: domain.BeadTypeFeature}, "feat: add dark mode"},
		{domain.Bead{ID: "fx-1", Title: "Bump deps", Type: domain.BeadTypeChore}, "chore: bump deps"},
		{domain.Bead{ID: "fx-1", Title: "Tidy  the\tREADME", Type: domain.BeadTypeTask}, "chore: tidy the README"},
		{domain.Bead{ID: "fx-1", Title: "Spike caching", Type: domain.BeadTypeSpike}, "feat: spike caching"},
		{domain.Bead{ID: "fx-1", Title: "Untyped"}, "feat: untyped"},
		{domain.Bead{ID: "fx-1", Title: "Énorme refonte", Type: domain.BeadTypeFeature}, "feat: énorme refonte"},
		{domain.Bead{ID: "fx-1", Title: "fix(rooms): keep the scroll position", Type: domain.BeadTypeFeature}, "fix(rooms): keep the scroll position"},
		{domain.Bead{ID: "fx-1", Title: "feat!: drop the v1 API", Type: domain.BeadTypeBug}, "feat!: drop the v1 API"},
		{domain.Bead{ID: "fx-1", Title: "Note: not a type", Type: domain.BeadTypeBug}, "fix: note: not a type"},
		{domain.Bead{ID: "fx-1", Title: " ", Type: domain.BeadTypeBug}, "fix: bead fx-1"},
	}
	for _, tc := range cases {
		assert.Equal(t, tc.want, ConventionalPRTitle(tc.bead), tc.bead.Title)
		assert.Regexp(t, `^[a-z]+(\([^)]*\))?!?: \S`, ConventionalPRTitle(tc.bead), "the shape amannn/action-semantic-pull-request accepts")
	}
	long := ConventionalPRTitle(domain.Bead{ID: "fx-1", Title: strings.Repeat("x", 500), Type: domain.BeadTypeBug})
	assert.LessOrEqual(t, len(long), maxPRTitleLen)
	assert.True(t, strings.HasPrefix(long, "fix: x"))
}

