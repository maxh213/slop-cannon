// docsRepoFile is docs/cli.md relative to this package.
var docsRepoFile = filepath.Join("..", "..", filepath.FromSlash(DocsPath))

// TestCLIDocsAreCurrent fails when docs/cli.md no longer matches the command
// tree. `make docs-cli` regenerates it; UPDATE_GOLDEN=1 (make update-golden)
// rewrites it from here as well, so one command refreshes every generated
// file after a help-text change.
func TestCLIDocsAreCurrent(t *testing.T) {
	want, err := Docs()
	require.NoError(t, err)
	if os.Getenv("UPDATE_GOLDEN") != "" {
		require.NoError(t, os.WriteFile(docsRepoFile, []byte(want), 0o644))
		return
	}
	got, err := os.ReadFile(docsRepoFile)
	require.NoError(t, err, "missing %s; run `make docs-cli`", DocsPath)
	require.Equal(t, want, string(got), "%s is stale; run `make docs-cli`", DocsPath)
}

func TestCLIDocsIsDeterministic(t *testing.T) {
	a, err := Docs()
	require.NoError(t, err)
	b, err := Docs()
	require.NoError(t, err)
	require.Equal(t, a, b)

	var buf bytes.Buffer
	require.NoError(t, WriteDocs(&buf, NewRootCommand(io.Discard)))
	require.Equal(t, a, buf.String())
}

func TestCLIDocsCoverEveryCommand(t *testing.T) {
	docs, err := Docs()
	require.NoError(t, err)
	require.True(t, strings.HasPrefix(docs, "# sc command reference\n"))
	require.Contains(t, docs, "Generated by `make docs-cli`")

	root := NewRootCommand(io.Discard)
	root.InitDefaultHelpCmd()
	for _, c := range docsCommands(root) {
		path := c.CommandPath()
		require.Contains(t, docs, "\n## "+path+"\n", "section for %s", path)
		require.Contains(t, docs, "- ["+path+"](#"+docsAnchor(c)+") — "+c.Short+"\n", "index entry for %s", path)
	}
	// Nested commands get their own sections and anchors.
	require.Contains(t, docs, "\n## sc config show\n")
	require.Contains(t, docs, "(#sc-config-show)")
	// Hidden commands never appear.
	require.NotContains(t, docs, "__complete")

	// Flags: the root shows its own (run + global) flags, children show
	// the global flags as inherited.
	require.Contains(t, docs, "## sc\n\n")
	require.Contains(t, docs, "--review-prs")
	require.Contains(t, docs, "### Options inherited from parent commands\n\n```\n      --global")
	require.Contains(t, docs, "-h, --help")

	// Examples and synopsis come straight from the commands.
	require.Contains(t, docs, "sc cartridge --add claude --model fable")
	require.Contains(t, docs, "\n### Synopsis\n\n"+strings.TrimRight(rootLong, "\n")+"\n")
}

func TestCLIDocsHaveNoMachineSpecificText(t *testing.T) {
	docs, err := Docs()
	require.NoError(t, err)
	home, err := os.UserHomeDir()
	require.NoError(t, err)
	require.NotContains(t, docs, home)
	cwd, err := os.Getwd()
	require.NoError(t, err)
	require.NotContains(t, docs, cwd)
	require.NotRegexp(t, regexp.MustCompile(`\d{4}-\d{2}-\d{2}`), docs, "dates would make the file churn")
}

func TestCLIDocsAnchor(t *testing.T) {
	root := NewRootCommand(io.Discard)
	require.Equal(t, "sc", docsAnchor(root))
	for _, c := range root.Commands() {
		if c.Name() == "config" {
			for _, s := range c.Commands() {
				require.Equal(t, "sc-config-"+s.Name(), docsAnchor(s))
			}
		}
	}
}
