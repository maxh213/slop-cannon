package testutil

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

// shimMarker is an empty file placed in every FakeBin directory so that
// RealBinary can skip it when looking for the genuine executable.
const shimMarker = ".sc-fakebin"

const (
	// recordSep terminates one invocation record in the log (ASCII RS).
	recordSep = 0x1e
	// fieldSep separates the fields of one record (NUL, which argv strings
	// can never contain).
	fieldSep = 0x00
)

// Shim is a fake executable installed on PATH by FakeBin.
type Shim struct {
	// Name is the command name, for example "bd".
	Name string
	// Path is the absolute path of the generated script.
	Path string
	// Dir is the directory prepended to PATH; it holds the script, the
	// invocation log, and captured stdin files.
	Dir string
	// LogPath is the file the shim appends one record per invocation to.
	LogPath string
}

// Invocation is one recorded call of a shim, in call order.
type Invocation struct {
	// Seq is the 1-based position of the call in the shim's log.
	Seq int
	// Name is the shim's command name.
	Name string
	// Dir is the working directory the shim was run in.
	Dir string
	// Args are the arguments after the command name.
	Args []string
	// Stdin is the captured standard input, only when the shim was created
	// with WithStdinCapture.
	Stdin string
}

// ShimOption customises FakeBin.
type ShimOption func(*shimConfig)

type shimConfig struct {
	captureStdin bool
}

// WithStdinCapture makes the shim read all of its standard input into a file
// before the script runs and exposes it as $SC_FAKEBIN_STDIN. Invocations
// then carry the captured text. Only use it for callers that always provide
// stdin (or close it), because the shim blocks until EOF.
func WithStdinCapture() ShimOption {
	return func(c *shimConfig) { c.captureStdin = true }
}

// FakeBin installs a POSIX shell script named name in a fresh directory that
// is prepended to PATH for the rest of the test, so any subprocess that
// looks up name runs the script instead of the real tool. It is meant for
// intercepting bd, gh, and git.
//
// Every invocation is appended to a log before script runs, so Invocations
// returns the calls in the order they happened even when they overlap.
// script is a shell fragment executed after the recording prologue; its exit
// status becomes the shim's exit status. It can use "$@" and these variables:
//
//	SC_FAKEBIN_NAME   the command name
//	SC_FAKEBIN_DIR    the shim directory (scratch space for the script)
//	SC_FAKEBIN_LOG    the invocation log
//	SC_FAKEBIN_SEQ    the 1-based sequence number of this call
//	SC_FAKEBIN_REAL   the real executable of the same name, or empty
//	SC_FAKEBIN_STDIN  file holding captured stdin (WithStdinCapture only)
//
// FakeBin uses t.Setenv, so it cannot be called from a parallel test.
func FakeBin(t testing.TB, name, script string, opts ...ShimOption) *Shim {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("testutil.FakeBin needs a POSIX shell")
	}
	if name == "" || strings.ContainsAny(name, `/\`) {
		t.Fatalf("testutil: invalid shim name %q", name)
	}
	cfg := shimConfig{}
	for _, o := range opts {
		o(&cfg)
	}

	real, err := RealBinary(name)
	if err != nil {
		real = ""
	}

	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, shimMarker), nil, 0o644); err != nil {
		t.Fatalf("testutil: writing shim marker: %v", err)
	}
	s := &Shim{
		Name:    name,
		Path:    filepath.Join(dir, name),
		Dir:     dir,
		LogPath: filepath.Join(dir, "invocations.log"),
	}
	if err := os.WriteFile(s.LogPath, nil, 0o644); err != nil {
		t.Fatalf("testutil: creating shim log: %v", err)
	}

	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by slop-cannon internal/testutil.FakeBin. Do not edit.\n")
	b.WriteString("SC_FAKEBIN_NAME=" + shellQuote(name) + "\n")
	b.WriteString("SC_FAKEBIN_DIR=" + shellQuote(dir) + "\n")
	b.WriteString("SC_FAKEBIN_LOG=" + shellQuote(s.LogPath) + "\n")
	b.WriteString("SC_FAKEBIN_REAL=" + shellQuote(real) + "\n")
	b.WriteString("export SC_FAKEBIN_NAME SC_FAKEBIN_DIR SC_FAKEBIN_LOG SC_FAKEBIN_REAL\n")
	// Serialise recording with a mkdir lock so concurrent calls never
	// interleave their records and sequence numbers stay unique.
	b.WriteString(`_sc_lock="$SC_FAKEBIN_DIR/.lock"
while ! mkdir "$_sc_lock" 2>/dev/null; do sleep 0.01; done
SC_FAKEBIN_SEQ=$(( $(tr -cd '\036' < "$SC_FAKEBIN_LOG" | wc -c) + 1 ))
SC_FAKEBIN_STDIN=''
`)
	if cfg.captureStdin {
		b.WriteString(`SC_FAKEBIN_STDIN="$SC_FAKEBIN_DIR/stdin.$SC_FAKEBIN_SEQ"
cat > "$SC_FAKEBIN_STDIN"
`)
	}
	b.WriteString(`{ printf '%s\0' "$SC_FAKEBIN_NAME" "$PWD" "$SC_FAKEBIN_STDIN" "$@"; printf '\036'; } >> "$SC_FAKEBIN_LOG"
rmdir "$_sc_lock"
export SC_FAKEBIN_SEQ SC_FAKEBIN_STDIN
# ---- test-provided script ----
`)
	b.WriteString(script)
	b.WriteString("\n")

	if err := os.WriteFile(s.Path, []byte(b.String()), 0o755); err != nil {
		t.Fatalf("testutil: writing shim %s: %v", name, err)
	}

	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
	return s
}

// Invocations parses the log and returns every call recorded so far, in
// order. Captured stdin is loaded when present.
func (s *Shim) Invocations(t testing.TB) []Invocation {
	t.Helper()
	data, err := os.ReadFile(s.LogPath)
	if err != nil {
		t.Fatalf("testutil: reading shim log: %v", err)
	}
	var calls []Invocation
	for i, rec := range bytes.Split(data, []byte{recordSep}) {
		if len(rec) == 0 {
			continue
		}
		fields := bytes.Split(rec, []byte{fieldSep})
		// Every field is NUL-terminated, so the last element is empty.
		if n := len(fields); n > 0 && len(fields[n-1]) == 0 {
			fields = fields[:n-1]
		}
		if len(fields) < 3 {
			t.Fatalf("testutil: malformed shim record %d: %q", i+1, rec)
		}
		inv := Invocation{Seq: len(calls) + 1, Name: string(fields[0]), Dir: string(fields[1])}
		if stdinFile := string(fields[2]); stdinFile != "" {
			in, err := os.ReadFile(stdinFile)
			if err != nil {
				t.Fatalf("testutil: reading captured stdin: %v", err)
			}
			inv.Stdin = string(in)
		}
		inv.Args = make([]string, 0, len(fields)-3)
		for _, f := range fields[3:] {
			inv.Args = append(inv.Args, string(f))
		}
		calls = append(calls, inv)
	}
	return calls
}

// ArgLists returns just the argument lists of every recorded call, which is
// the convenient shape for assertions.
func (s *Shim) ArgLists(t testing.TB) [][]string {
	t.Helper()
	calls := s.Invocations(t)
	out := make([][]string, len(calls))
	for i, c := range calls {
		out[i] = c.Args
	}
	return out
}

// Reset empties the invocation log so a test can assert on one phase at a
// time. Sequence numbers restart at 1.
func (s *Shim) Reset(t testing.TB) {
	t.Helper()
	if err := os.WriteFile(s.LogPath, nil, 0o644); err != nil {
		t.Fatalf("testutil: resetting shim log: %v", err)
	}
}

// Command returns an exec.Cmd that runs the shim through PATH lookup, the
// way production code would find it.
func (s *Shim) Command(t testing.TB, args ...string) *exec.Cmd {
	t.Helper()
	path, err := exec.LookPath(s.Name)
	if err != nil {
		t.Fatalf("testutil: shim %s not on PATH: %v", s.Name, err)
	}
	if path != s.Path {
		t.Fatalf("testutil: PATH resolves %s to %s, want %s", s.Name, path, s.Path)
	}
	return exec.Command(path, args...)
}

// shellQuote wraps s in single quotes for a POSIX shell.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
